import assert from 'node:assert/strict';

export async function verifyHarnessCalendar(page, service) {
  const dialog = page.getByRole('dialog');
  await page.getByRole('button', { name: '+ New table', exact: true }).click();
  await dialog.getByLabel('Table name', { exact: true }).fill('Harness calendar');
  await dialog.getByRole('button', { name: 'Create table', exact: true }).click();
  await page.getByRole('heading', { name: 'Harness calendar', exact: true }).waitFor();
  let table = service.listTables().find(table => table.name === 'Harness calendar');
  table = service.createField(table.id, { expectedVersion: table.version, name: 'Start', type: 'datetime' });
  const start = table.fields[1].id;
  const record = service.createRecords(table.id, [{ values: { [table.primaryFieldId]: 'Local-zone meeting', [start]: '2024-02-28T18:30:00.000Z' } }]).records[0];
  await page.getByRole('button', { name: 'Reload', exact: true }).click();
  await page.getByText('1 record · 2 fields', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'New view', exact: true }).click();
  await dialog.getByLabel('View name', { exact: true }).fill('Meetings');
  await dialog.getByLabel('View type', { exact: true }).selectOption('calendar');
  await dialog.getByLabel('Calendar time zone', { exact: true }).fill('Asia/Shanghai');
  await dialog.getByRole('button', { name: 'Create view', exact: true }).click();
  const calendar = page.getByRole('region', { name: 'Meetings calendar', exact: true });
  await calendar.getByLabel('Calendar month', { exact: true }).fill('2024-02');
  const day = calendar.locator('[data-calendar-date="2024-02-29"]');
  await day.getByRole('button', { name: /Local-zone meeting/ }).waitFor();
  await day.getByText('2:30 AM', { exact: true }).waitFor();
  assert.equal(await calendar.locator('[data-calendar-date="2024-02-28"] .calendar-preview').count(), 0);
  await day.locator('.calendar-day-heading').click();
  const pane = calendar.getByRole('complementary', { name: 'Calendar records', exact: true });
  await pane.getByText('Feb 29, 2024, 2:30 AM GMT+8', { exact: true }).waitFor();
  await pane.getByRole('button', { name: 'Local-zone meeting', exact: true }).click();
  await dialog.getByLabel('Name', { exact: true }).fill('Edited meeting');
  await dialog.getByRole('button', { name: 'Save record', exact: true }).click();
  await pane.getByRole('button', { name: 'Edited meeting', exact: true }).waitFor();
  assert.equal(service.getRecord(table.id, record.id).values[table.primaryFieldId], 'Edited meeting');
  await pane.getByRole('button', { name: '+ New record on this date', exact: true }).click();
  await dialog.getByLabel('Name', { exact: true }).fill('Midnight in the calendar zone');
  await dialog.getByRole('button', { name: 'Create record', exact: true }).click();
  await pane.getByRole('button', { name: 'Midnight in the calendar zone', exact: true }).waitFor();
  const created = service.queryRecords(table.id, { search: 'Midnight in the calendar zone' }).records[0];
  assert.equal(created.values[start], '2024-02-28T16:00:00.000Z');
  const view = service.listViews(table.id).find(view => view.name === 'Meetings');
  assert.deepEqual(view.calendar, { startFieldId: start, timeZone: 'Asia/Shanghai' });
  await page.screenshot({ path: '.artifacts/desktop-harness-calendar-time-zone.png' });
  table = service.createField(table.id, { expectedVersion: table.version, name: 'Created', type: 'createdTime' });
  const automatic = table.fields.at(-1).id;
  service.createView(table.id, { name: 'Created dates', type: 'calendar', calendar: { startFieldId: automatic, timeZone: 'UTC' } });
  await page.getByRole('button', { name: 'Reload', exact: true }).click();
  await page.getByRole('tab', { name: 'Created dates', exact: true }).click();
  const automaticCalendar = page.getByRole('region', { name: 'Created dates calendar', exact: true });
  const date = service.getRecord(table.id, record.id).values[automatic].slice(0, 10);
  await automaticCalendar.getByLabel('Calendar month', { exact: true }).fill(date.slice(0, 7));
  await automaticCalendar.locator('[data-calendar-day="' + date + '"]:enabled').click();
  await automaticCalendar.getByText('This start field is read-only. Use New record to create records from their inputs.', { exact: true }).waitFor();
  assert.equal(await automaticCalendar.getByRole('button', { name: '+ New record on this date', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: '+ New record', exact: true }).isDisabled(), false);
  await page.getByRole('button', { name: 'Delete table', exact: true }).click();
  await dialog.getByRole('button', { name: 'Delete table', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  console.log('Installed Harness calendar creation, time-zone presentation and record editing passed.');
}
