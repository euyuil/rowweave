import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parseCsv } from '../../../dist/packages/core/src/csv.js';

export async function verifyCsvWorkflow(page, application, directory) {
  await page.getByRole('button', { name: '+ New table', exact: true }).click();
  await page.getByLabel('Table name', { exact: true }).fill('CSV lab');
  await page.getByRole('dialog').getByRole('button', { name: 'Create table', exact: true }).click();
  await page.getByRole('heading', { name: 'CSV lab', exact: true }).waitFor();
  const call = (path, method = 'GET', body) => page.evaluate(async ({ path, method, body }) => {
    const connection = await window.rowweave.connection();
    const response = await fetch(`${connection.url}${path}`, { method, headers: { Authorization: `Bearer ${connection.token}`, 'Content-Type': 'application/json' },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error.message);
    return result;
  }, { path, method, body });
  let table = (await call('/tables')).find(table => table.name === 'CSV lab');
  table = await call(`/tables/${table.id}/fields`, 'POST', { expectedVersion: table.version, name: 'Count', type: 'number', required: true, defaultValue: 0 });
  table = await call(`/tables/${table.id}/fields`, 'POST', { expectedVersion: table.version, name: 'Notes', type: 'multiline' });
  const [name, count, notes] = table.fields.map(field => field.id);
  const records = async () => (await call(`/tables/${table.id}/records?offset=0&limit=20`)).records;
  const reload = async () => {
    await page.getByRole('button', { name: 'Reload', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.grid-host')?.getAttribute('aria-busy') === 'false');
  };
  await reload();
  await page.getByText('0 records · 3 fields', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Import CSV', exact: true }).click();
  const upload = csv => page.getByLabel('CSV file', { exact: true }).setInputFiles({ name: 'tasks.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
  const preview = () => page.getByRole('button', { name: 'Preview CSV', exact: true }).click();
  await upload('Label,Budget,Notes,Skipped\nFirst,2,detail,ignored\nSecond,not a number,detail,ignored');
  await preview();
  await page.getByText('2 rows · 0 invalid', { exact: true }).waitFor();
  await page.getByLabel('Map column 1', { exact: true }).selectOption(name);
  await page.getByLabel('Map column 2', { exact: true }).selectOption(count);
  assert.equal(await page.getByRole('button', { name: 'Import 2 records', exact: true }).isDisabled(), true);
  await preview();
  await page.getByText('2 rows · 1 invalid', { exact: true }).waitFor();
  await page.getByText(/Row 3: Count: enter a decimal number/).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Import 2 records', exact: true }).isDisabled(), true);
  assert.deepEqual(await records(), []);
  await page.screenshot({ path: '.artifacts/desktop-csv-validation.png' });
  await upload('Name,Count,' + Array.from({ length: 10 }, (_, i) => `Extra ${i + 1}`).join(',') + '\nwide,4,' + Array(10).fill('').join(','));
  await preview();
  await page.getByText('1 row · 0 invalid', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Next columns', exact: true }).click();
  await page.getByLabel('Map column 11', { exact: true }).selectOption(notes);
  await preview();
  await page.getByText('1 row · 0 invalid', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Previous columns', exact: true }).click();
  assert.equal(await page.getByLabel('Map column 2', { exact: true }).inputValue(), count);
  await page.getByLabel('First row contains column names', { exact: true }).uncheck();
  await preview();
  await page.getByText('2 rows · 0 invalid', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Map column 1', { exact: true }).inputValue(), '');
  assert.equal(await page.getByRole('button', { name: 'Import 2 records', exact: true }).isDisabled(), true);
  await page.getByLabel('First row contains column names', { exact: true }).check();
  const csv = 'Name,Count,Notes,Ignored\r\n"中文, 🌱",12.5,"Line one\n中文第二行",unused\r\n"",0,,unused\r\n,3,"",unused\r\n';
  await upload(csv);
  await preview();
  await page.getByText('3 rows · 0 invalid', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Map column 4', { exact: true }).inputValue(), '');
  await page.screenshot({ path: '.artifacts/desktop-csv-preview.png' });
  await page.getByRole('button', { name: 'Import 3 records', exact: true }).click();
  await page.getByText('Imported 3 records.', { exact: true }).waitFor();
  await page.getByText('3 records · 3 fields', { exact: true }).waitFor();
  const imported = await records();
  assert.equal(imported[0].values[name], '中文, 🌱');
  assert.equal(imported[0].values[notes], 'Line one\n中文第二行');
  assert.equal(imported[1].values[name], '');
  assert.equal(imported[1].values[notes], null);
  assert.equal(imported[2].values[name], null);
  assert.equal(imported[2].values[notes], '');

  const view = await call(`/tables/${table.id}/views`, 'POST', { name: 'Export subset', query: {
    filter: { conjunction: 'and', conditions: [{ fieldId: count, operator: 'gt', value: 0 }] }, sort: [{ fieldId: count, direction: 'desc' }] },
    columns: [{ fieldId: count, width: 120, hidden: false }, { fieldId: name, width: 180, hidden: false }, { fieldId: notes, width: 180, hidden: true }] });
  await reload();
  await page.getByLabel('Current view', { exact: true }).selectOption(view.id);
  await page.getByText('2 records · 2 fields', { exact: true }).waitFor();
  await page.getByLabel('Search records', { exact: true }).fill('中文');
  await page.getByText('1 record · 2 fields', { exact: true }).waitFor();
  const exportPath = join(directory, 'export.csv');
  await application.evaluate(({ dialog }, filePath) => {
    globalThis.csvOriginalSaveDialog = dialog.showSaveDialog;
    dialog.showSaveDialog = async (_window, options) => {
      globalThis.csvSaveOptions = options;
      return { canceled: false, filePath };
    };
  }, exportPath);
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  await page.getByRole('button', { name: 'Save CSV', exact: true }).click();
  await page.getByText('CSV saved.', { exact: true }).waitFor();
  const saved = await readFile(exportPath, 'utf8');
  assert.ok(saved.startsWith('\uFEFF'));
  assert.deepEqual([...parseCsv(saved)].map(row => row.cells.map(cell => cell.text)), [['Count', 'Name'], ['12.5', '中文, 🌱']]);
  const options = await application.evaluate(() => globalThis.csvSaveOptions);
  assert.equal(options.defaultPath, 'RowWeave-CSV lab-Export subset.csv');
  assert.deepEqual(options.filters, [{ name: 'CSV files', extensions: ['csv'] }]);
  await page.getByLabel('Export scope', { exact: true }).selectOption('table');
  await page.getByRole('button', { name: 'Save CSV', exact: true }).click();
  await page.getByText('CSV saved.', { exact: true }).waitFor();
  const whole = await readFile(exportPath, 'utf8');
  assert.equal([...parseCsv(whole)].length, 4);
  assert.ok(whole.includes('Name,Count,Notes\r\n'));
  await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true, filePath: '' }); });
  await page.getByRole('button', { name: 'Save CSV', exact: true }).click();
  await page.getByText('Save canceled. No file was written.', { exact: true }).waitFor();
  assert.equal(await readFile(exportPath, 'utf8'), whole);
  await application.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, join(directory, 'missing', 'export.csv'));
  await page.getByRole('button', { name: 'Save CSV', exact: true }).click();
  await page.getByRole('dialog').getByRole('alert').waitFor();
  assert.equal(await page.getByText('CSV saved.', { exact: true }).count(), 0);
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await application.evaluate(({ dialog }) => { dialog.showSaveDialog = globalThis.csvOriginalSaveDialog; });

  await page.getByLabel('Current view', { exact: true }).selectOption({ label: 'All records' });
  await page.getByRole('button', { name: 'Import CSV', exact: true }).click();
  await upload('Name,Count\nAfter schema change,1');
  await preview();
  await page.getByText('1 row · 0 invalid', { exact: true }).waitFor();
  table = await call(`/tables/${table.id}/fields`, 'POST', { expectedVersion: table.version, name: 'Defaulted', type: 'text', defaultValue: 'new default' });
  await page.getByRole('button', { name: 'Import 1 record', exact: true }).click();
  await page.getByRole('button', { name: 'Reload schema', exact: true }).waitFor();
  assert.equal((await records()).length, 3);
  await page.getByRole('button', { name: 'Reload schema', exact: true }).click();
  await preview();
  await page.getByText('1 row · 0 invalid', { exact: true }).waitFor();
  const viewsRoute = `**/tables/${table.id}/views`;
  await page.route(viewsRoute, route => route.abort());
  await page.getByRole('button', { name: 'Import 1 record', exact: true }).click();
  await page.getByText('Imported 1 record.', { exact: true }).waitFor();
  await page.getByText(/Imported records saved, but refreshing failed/).waitFor();
  assert.equal((await records())[3].values[table.fields[3].id], 'new default');
  await page.unroute(viewsRoute);
  await reload();

  await page.getByRole('button', { name: 'Import CSV', exact: true }).click();
  await page.getByLabel('CSV file', { exact: true }).setInputFiles({ name: 'bad-encoding.csv', mimeType: 'text/csv', buffer: Buffer.from([0xff, 0xfe, 0x41]) });
  await page.getByText(/not valid UTF-8/).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Preview CSV', exact: true }).isDisabled(), true);
  await upload('Name,Count\nUncertain,1');
  await preview();
  await page.getByText('1 row · 0 invalid', { exact: true }).waitFor();
  const importRoute = `**/tables/${table.id}/import`;
  await page.route(importRoute, async route => {
    const response = await route.fetch();
    assert.equal(response.status(), 201);
    await route.abort();
  });
  await page.getByRole('button', { name: 'Import 1 record', exact: true }).click();
  await page.getByText(/records may already be saved/).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Import 1 record', exact: true }).isDisabled(), true);
  await page.unroute(importRoute);
  await page.getByRole('button', { name: 'Close and reload', exact: true }).click();
  assert.equal((await records()).length, 5);
  await page.getByText('5 records · 4 fields', { exact: true }).waitFor();
  const bounds = await page.locator('canvas').first().boundingBox();
  await page.mouse.click(bounds.x + 100, bounds.y + 58);
  await page.keyboard.press('Enter');
  await page.getByRole('textbox', { name: 'Cell value', exact: true }).fill('Unsaved');
  await page.keyboard.press('Enter');
  await page.getByText('1 unsaved cell', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Import CSV', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Export CSV', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByText('All changes saved', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Delete table', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete table', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
}
