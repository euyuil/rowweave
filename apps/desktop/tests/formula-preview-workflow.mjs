import assert from 'node:assert/strict';

export async function verifyFormulaPreviewWorkflow(page) {
  const dialog = page.getByRole('dialog');
  const call = (path, method = 'GET', input) => page.evaluate(async ({ path, method, input }) => {
    const connection = await window.rowweave.connection();
    const response = await fetch(connection.url + path, { method, headers: { Authorization: 'Bearer ' + connection.token, 'Content-Type': 'application/json' },
      ...(input ? { body: JSON.stringify(input) } : {}) });
    if (!response.ok) throw new Error(await response.text()); return response.json();
  }, { path, method, input });
  await page.getByRole('button', { name: '+ New table', exact: true }).click();
  await page.getByLabel('Table name', { exact: true }).fill('Formula previews');
  await dialog.getByRole('button', { name: 'Create table', exact: true }).click();
  await page.getByRole('heading', { name: 'Formula previews', exact: true }).waitFor();
  const table = (await call('/tables')).find(table => table.name === 'Formula previews');
  const path = '/tables/' + table.id;
  await page.getByRole('button', { name: 'Manage fields', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add field', exact: true }).click();
  await dialog.getByLabel('Field type', { exact: true }).selectOption('formula');
  const expression = dialog.getByLabel('Formula', { exact: true });
  const preview = dialog.getByRole('region', { name: 'Formula preview', exact: true });
  const calculate = () => preview.getByRole('button', { name: 'Preview formula', exact: true }).click();
  const result = preview.getByLabel('Preview result', { exact: true });
  await expression.fill('LEN(["Name"]) * 2');
  await calculate();
  await preview.getByText('The formula is valid. Add a record to preview its result; this table is empty.', { exact: true }).waitFor();
  const rows = (await call(path + '/records', 'POST', Array.from({ length: 52 }, (_, index) => ({ values: {
    [table.primaryFieldId]: index === 0 ? 'Alpha' : index === 1 ? 'Beta' : 'Sample ' + (index + 1),
  } })))).records;
  const history = await call(path + '/batches/query', 'POST', {});
  await calculate(); await result.filter({ hasText: /^10$/ }).waitFor();
  assert.equal(await dialog.getByLabel('Field name', { exact: true }).inputValue(), '', 'Preview does not require a field name or save the schema.');
  await expression.fill('1 / 0'); await result.waitFor({ state: 'detached' });
  await calculate(); await preview.getByRole('alert').filter({ hasText: /zero/ }).waitFor();
  await expression.fill('LEN(["Missing"])'); await calculate();
  await preview.getByRole('alert').filter({ hasText: /Choose a current field/ }).waitFor();
  await expression.fill('1 +'); await calculate();
  await preview.getByRole('alert').waitFor();
  await dialog.getByLabel('Result type', { exact: true }).selectOption('date');
  await expression.fill('DATEADD(DATE(2024, 1, 31), 1, "month")'); await calculate();
  await result.filter({ hasText: /^2024-02-29$/ }).waitFor();
  await dialog.getByLabel('Result type', { exact: true }).selectOption('text');
  const longText = 'x'.repeat(2000) + '\nsecond';
  await expression.fill(JSON.stringify(longText)); await calculate(); await result.waitFor();
  assert.equal(await result.textContent(), longText);
  assert.ok(await preview.evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'Long results must wrap inside the preview.');
  await dialog.getByLabel('Result type', { exact: true }).selectOption('number');
  await result.waitFor({ state: 'detached' });
  await expression.fill('LEN(["Name"]) * 2');
  await preview.getByText('Choose a sample record', { exact: true }).click();
  const ready = () => page.waitForFunction(() => document.querySelector('[aria-label="Sample records"]')?.getAttribute('aria-busy') === 'false');
  await preview.getByRole('radio', { name: 'Alpha', exact: true }).waitFor();
  await ready(); assert.equal(await preview.getByRole('radio').count(), 50);
  await preview.getByRole('button', { name: 'Next samples', exact: true }).click();
  await preview.getByRole('radio', { name: 'Sample 52', exact: true }).waitFor(); await ready();
  assert.equal(await preview.getByRole('radio').count(), 2);
  await preview.getByRole('radio', { name: 'Sample 52', exact: true }).check();
  await calculate(); await result.filter({ hasText: /^18$/ }).waitFor();
  await preview.getByLabel('Find sample records', { exact: true }).fill('Beta');
  await preview.getByRole('radio', { name: 'Beta', exact: true }).waitFor(); await ready();
  await preview.getByRole('radio', { name: 'Beta', exact: true }).check(); await result.waitFor({ state: 'detached' });
  await calculate(); await result.filter({ hasText: /^8$/ }).waitFor();
  await dialog.getByLabel('Number format', { exact: true }).selectOption('currency');
  await dialog.getByLabel('Currency code', { exact: true }).fill('U');
  await calculate(); await result.filter({ hasText: /^8$/ }).waitFor();
  await dialog.getByLabel('Number format', { exact: true }).selectOption('decimal');
  await preview.getByText('Choose a sample record', { exact: true }).click();
  await result.scrollIntoViewIfNeeded();
  await page.screenshot({ path: '.artifacts/desktop-formula-preview.png' });
  assert.deepEqual((await call(path)).fields, table.fields);
  assert.deepEqual((await call(path + '/query', 'POST', {})).records, rows);
  assert.deepEqual(await call(path + '/batches/query', 'POST', {}), history);
  await dialog.getByLabel('Field name', { exact: true }).fill('Name length');
  await dialog.getByRole('button', { name: 'Save field', exact: true }).click();
  await page.getByRole('dialog', { name: 'Manage fields', exact: true }).waitFor();
  const saved = await call(path), formula = saved.fields.at(-1);
  assert.equal((await call(path + '/records/' + rows[1].id)).values[formula.id], 8);
  await dialog.getByRole('group', { name: 'Name length', exact: true }).getByRole('button', { name: 'Configure', exact: true }).click();
  await expression.fill('LEN(["Name"]) * 3'); await calculate();
  await result.filter({ hasText: /^15$/ }).waitFor();
  await call(path + '/fields/' + table.primaryFieldId, 'PATCH', { expectedVersion: saved.version, description: 'Changed elsewhere' });
  await calculate(); await preview.getByRole('alert').filter({ hasText: /schema changed/ }).waitFor();
  assert.equal(await expression.inputValue(), 'LEN(["Name"]) * 3', 'A schema conflict must retain the draft.');
  assert.deepEqual((await call(path)).fields.at(-1).formula, formula.formula);
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await dialog.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Reload', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.grid-host')?.getAttribute('aria-busy') === 'false');
  await page.getByRole('button', { name: 'Delete table', exact: true }).click();
  await dialog.getByRole('button', { name: 'Delete table', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
}
